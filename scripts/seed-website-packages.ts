// Packages from the client's sheet "FULL BODY PACAKAGE FOR WEBSIDE.xlsx" (2026-11-27): the MD CARE
// full body prices, and the Anaemia, Pregnancy / Infertility, Cardiac, Cancer and Diabetes packages —
// names, website prices, MRPs and included tests as the sheet lists them (spelling fixed).
//
// What it does, safe to run again (nothing is duplicated; rows are found by slug / testCode / code):
//  1. Markers (atomic parameters, code MK-…) the sheet names that don't exist yet are created.
//  2. Tests the packages need that don't exist yet are created. Tests the sheet prices on their own
//     (Lipid Profile Advance, Cholesterol, HDL, LDL, PSA Free) are bookable at that price; the rest
//     are hidden at ₹0 like the MD CARE ones — shown inside packages, bookable alone once admin prices them.
//     A test with no markers yet gets the ones the sheet lists (existing links are never changed).
//  3. CA 125 and PSA total get the sheet's prices.
//  4. MD CARE packages get the sheet's prices (and Basic Care its eGFR) — run
//     scripts/seed-md-care-packages.ts first on a database that doesn't have them yet.
//  5. New packages are created with their tests.
//  6. City prices: each city that already lists prices for packages (or tests) gets the new ones too.
//  7. Labs: every active lab that offers packages (or tests) is set to offer these too — without that
//     a home booking finds no lab ("not yet available at this address").
//
// Usage: npx tsx scripts/seed-website-packages.ts            (dry run: prints what it would do)
//        npx tsx scripts/seed-website-packages.ts --apply    (writes)
