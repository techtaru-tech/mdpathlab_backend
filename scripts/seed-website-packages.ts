// Fasting when the package has fasting glucose or a lipid test in it.
const FASTING_KEYS = new Set(['glucose', 'lipid', 'lipidExt']);

// ---------------------------------------------------------------- run

const log = (s: string) => console.log((APPLY ? '' : '[dry run] ') + s);

async function main() {
  const categories = new Map((await prisma.category.findMany()).map((c) => [c.slug, c.id]));
  const categoryId = (slug: string) => {
    const id = categories.get(slug);
    if (!id) throw new Error(`Category "${slug}" not found`);
    return id;
  };

  // Every key a package or update uses must resolve before anything is written.
  for (const p of PACKAGES) for (const k of p.tests) if (!EXISTING[k] && !NEW_TESTS[k]) throw new Error(`${p.name}: unknown test "${k}"`);
  for (const t of Object.values(NEW_TESTS)) categoryId(t.category);
  for (const p of PACKAGES) categoryId(p.category);
  const ids = new Map<string, { itemType: PackageItemType; id: string }>();
  for (const [key, ref] of Object.entries(EXISTING)) {
    const row = ref.parameterSlug
      ? await prisma.parameter.findUnique({ where: { slug: ref.parameterSlug } })
      : await prisma.profile.findUnique({ where: { testCode: ref.testCode! } });
    if (!row) throw new Error(`Test "${key}" (${ref.parameterSlug ?? ref.testCode}) not found — run scripts/seed-md-care-packages.ts first?`);
    ids.set(key, { itemType: ref.itemType, id: row.id });
  }

  // 1. Markers
  const markerIds = new Map<string, string>();
  const wantedMarkers = new Set([...Object.values(NEW_TESTS).flatMap((t) => t.markers ?? []), ...Object.values(MARKERS_FOR_EXISTING).flat()]);
  let markersCreated = 0;
  for (const name of wantedMarkers) {
    const code = 'MK-' + slugify(name).toUpperCase();
    const existing =
      (await prisma.parameter.findUnique({ where: { code } })) ??
      (await prisma.parameter.findFirst({ where: { code: { not: null }, name: { equals: name, mode: 'insensitive' } } }));
    if (existing) {
      markerIds.set(name, existing.id);
      continue;
    }
    markersCreated++;
    log(`marker  + ${name}`);
    if (APPLY) {
      const row = await prisma.parameter.create({
        data: { name, slug: 'marker-' + slugify(name), code, mrp: 0, price: 0, reportTimeHours: 24, sampleCollection: 'HOME', status: 'ACTIVE' },
      });
      markerIds.set(name, row.id);
    }
  }

  const linkMarkers = async (profileId: string, label: string, markers: string[]) => {
    if (!markers.length || (await prisma.profileParameter.count({ where: { profileId } }))) return;
    log(`markers ${label}: ${markers.join(', ')}`);
    if (APPLY) await prisma.profileParameter.createMany({ data: markers.map((m) => ({ profileId, parameterId: markerIds.get(m)! })), skipDuplicates: true });
  };

  // 2. Tests
  let testsCreated = 0;
  const newBookable: string[] = [];
  for (const [key, t] of Object.entries(NEW_TESTS)) {
    let row = await prisma.profile.findUnique({ where: { testCode: t.testCode } });
    if (!row) {
      testsCreated++;
      const bookable = t.price != null;
      log(`test    + ${t.name} ${bookable ? `₹${t.price} (MRP ₹${t.mrp})` : '(hidden, ₹0)'}`);
      if (APPLY) {
        row = await prisma.profile.create({
          data: {
            testCode: t.testCode,
            name: t.name,
            slug: slugify(t.name),
            sampleType: t.sampleType ?? 'Blood',
            reportTimeHours: t.reportTimeHours ?? 24,
            fastingRequired: Boolean(t.fasting),
            fastingHours: t.fasting ? 10 : null,
            mrp: t.mrp ?? 0,
            price: t.price ?? 0,
            categoryId: categoryId(t.category),
            status: bookable ? 'ACTIVE' : 'INACTIVE',
          },
        });
      }
    }
    if (row) {
      ids.set(key, { itemType: 'PROFILE', id: row.id });
      await linkMarkers(row.id, t.name, t.markers ?? []);
      if (t.price != null && row.status === 'ACTIVE') newBookable.push(row.id);
    } else {
      ids.set(key, { itemType: 'PROFILE', id: `(new ${key})` });
    }
  }
  for (const [key, markers] of Object.entries(MARKERS_FOR_EXISTING)) await linkMarkers(ids.get(key)!.id, EXISTING[key]!.testCode!, markers);

  // 3. Existing tests' prices (and their city prices, which override them)
  for (const u of PRICE_UPDATES) {
    const { id } = ids.get(u.key)!;
    const row = await prisma.profile.findUniqueOrThrow({ where: { id } });
    if (row.price === u.price && row.mrp === u.mrp) continue;
    log(`price   ${row.name}: ₹${row.price}/${row.mrp} → ₹${u.price}/${u.mrp}`);
    if (APPLY) {
      await prisma.profile.update({ where: { id }, data: { price: u.price, mrp: u.mrp } });
      await prisma.cityPrice.updateMany({ where: { itemType: 'PROFILE', itemId: id }, data: { price: u.price, mrp: u.mrp } });
    }
  }

  // 4. MD CARE
  const mdCareIds: string[] = [];
  for (const m of MD_CARE) {
    const pkg = await prisma.package.findUnique({ where: { slug: m.slug }, include: { items: true } });
    if (!pkg) {
      console.warn(`MISSING ${m.slug} — run scripts/seed-md-care-packages.ts first, then this again`);
      continue;
    }
    mdCareIds.push(pkg.id);
    if (pkg.price !== m.price || pkg.mrp !== m.mrp) {
      log(`price   ${pkg.name}: ₹${pkg.price}/${pkg.mrp} → ₹${m.price}/${m.mrp}`);
      if (APPLY) {
        await prisma.package.update({ where: { id: pkg.id }, data: { price: m.price, mrp: m.mrp } });
        await prisma.cityPrice.updateMany({ where: { itemType: 'PACKAGE', itemId: pkg.id }, data: { price: m.price, mrp: m.mrp } });
      }
    }
    for (const key of m.addTests ?? []) {
      const t = ids.get(key)!;
      if (pkg.items.some((i) => (i.profileId ?? i.parameterId) === t.id)) continue;
      log(`item    ${pkg.name} + ${key}`);
      if (APPLY)
        await prisma.packageItem.create({
          data: { packageId: pkg.id, itemType: t.itemType, profileId: t.itemType === 'PROFILE' ? t.id : null, parameterId: t.itemType === 'PARAMETER' ? t.id : null },
        });
    }
  }

  // 5. Packages
  const newPackageIds: string[] = [];
  let packagesCreated = 0;
  for (const p of PACKAGES) {
    const slug = slugify(p.name);
    const existing = await prisma.package.findUnique({ where: { slug } });
    if (existing) {
      newPackageIds.push(existing.id);
      log(`exists  ${p.name}`);
      continue;
    }
    packagesCreated++;
    const fasting = p.tests.some((k) => FASTING_KEYS.has(k));
    log(`package + ${p.name} — ₹${p.price} (MRP ₹${p.mrp}), ${p.tests.length} tests${fasting ? ', fasting' : ''}`);
    if (!APPLY) continue;
    const pkg = await prisma.package.create({
      data: {
        name: p.name,
        slug,
        subtitle: p.subtitle ?? `${p.tests.length} tests`,
        price: p.price,
        mrp: p.mrp,
        reportTimeHours: p.reportTimeHours ?? 24,
        fastingRequired: fasting,
        fastingHours: fasting ? 10 : null,
        categoryId: categoryId(p.category),
        items: {
          create: p.tests.map((key) => {
            const t = ids.get(key)!;
            return { itemType: t.itemType, parameterId: t.itemType === 'PARAMETER' ? t.id : null, profileId: t.itemType === 'PROFILE' ? t.id : null };
          }),
        },
      },
    });
    newPackageIds.push(pkg.id);
  }

  // 6. City prices — only in cities that already list this kind of item (a city with none shows everything anyway).
  const priceOf = new Map<string, { price: number; mrp: number }>();
  for (const r of await prisma.package.findMany({ where: { id: { in: [...newPackageIds, ...mdCareIds] } } })) priceOf.set(r.id, { price: r.price, mrp: r.mrp });
  for (const r of await prisma.profile.findMany({ where: { id: { in: newBookable } } })) priceOf.set(r.id, { price: r.price, mrp: r.mrp });
  let cityRows = 0;
  for (const [itemType, itemIds] of [
    ['PACKAGE', [...newPackageIds, ...mdCareIds]],
    ['PROFILE', newBookable],
  ] as [CartItemType, string[]][]) {
    const cities = await prisma.cityPrice.findMany({ where: { itemType }, distinct: ['cityId'], select: { cityId: true } });
    for (const { cityId } of cities) {
      const have = new Set((await prisma.cityPrice.findMany({ where: { cityId, itemType, itemId: { in: itemIds } }, select: { itemId: true } })).map((r) => r.itemId));
      const missing = itemIds.filter((id) => !have.has(id) && priceOf.has(id));
      if (!missing.length) continue;
      cityRows += missing.length;
      if (APPLY) await prisma.cityPrice.createMany({ data: missing.map((itemId) => ({ cityId, itemType, itemId, ...priceOf.get(itemId)! })), skipDuplicates: true });
    }
  }

  // 7. Labs
  let labRows = 0;
  for (const [itemType, itemIds] of [
    ['PACKAGE', [...newPackageIds, ...mdCareIds]],
    ['PROFILE', newBookable],
  ] as [CartItemType, string[]][]) {
    const labs = await prisma.lab.findMany({ where: { status: 'ACTIVE', catalogueItems: { some: { itemType } } }, include: { catalogueItems: { where: { itemType } } } });
    for (const lab of labs) {
      const have = new Set(lab.catalogueItems.map((c) => c.itemId));
      const missing = itemIds.filter((id) => !have.has(id) && !id.startsWith('('));
      if (!missing.length) continue;
      labRows += missing.length;
      log(`lab     ${lab.name.trim()}: + ${missing.length} ${itemType.toLowerCase()}s`);
      if (APPLY) await prisma.labCatalogueItem.createMany({ data: missing.map((itemId) => ({ labId: lab.id, itemType, itemId })), skipDuplicates: true });
    }
  }

  console.log(
    `${APPLY ? 'Done' : 'Dry run'}: markers +${markersCreated}, tests +${testsCreated}, packages +${packagesCreated}, city prices +${cityRows}, lab offers +${labRows}.` +
      (APPLY ? '' : ' Nothing written — add --apply.'),
  );
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
